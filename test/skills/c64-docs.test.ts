// The c64-docs scripts (D80), run as the LLM runs them: a small project with
// knowledge, a PRG, and a source with its source map written by hand, so the
// tests need neither ACME nor Ghidra.

import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { after, test } from "node:test";

import { readPng } from "../../src/graphics.testkit.ts";

const SCRIPTS = resolve(import.meta.dirname, "../../skills");
const projects: string[] = [];
after(() => {
  for (const project of projects) rmSync(project, { recursive: true, force: true });
});

function run(root: string, script: string, ...args: string[]): { status: number | null; json: Record<string, unknown> } {
  const result = spawnSync(process.execPath, [...process.execArgv, join(SCRIPTS, script), ...args], { cwd: root, encoding: "utf8" });
  assert.equal(result.stderr, "", result.stderr);
  return { status: result.status, json: JSON.parse(result.stdout) as Record<string, unknown> };
}
const knowledge = (root: string, ...args: string[]) => run(root, "c64-knowledge/scripts/knowledge.ts", ...args);
const generate = (root: string, ...args: string[]) => run(root, "c64-docs/scripts/generate.ts", ...args);
const link = (root: string, ...args: string[]) => run(root, "c64-docs/scripts/link.ts", ...args);
const revisionOf = (root: string) => (knowledge(root, "revisions", "--limit", "1").json.revisions as Array<{ id: string }>)[0]!.id;

/** Writes the source files and a source map in the form of c64-source: each label and item on its line, after the mark line. */
function writeSource(root: string, revision: string, files: Record<string, Array<string | { label: string; address: number } | { item: string; start: number; end: number }>>): void {
  mkdirSync(join(root, "src"), { recursive: true });
  const labels: unknown[] = [];
  const items: unknown[] = [];
  const hex = (address: number) => `$${address.toString(16).padStart(4, "0")}`;
  for (const [file, lines] of Object.entries(files)) {
    const text = ["; Generated by c64-source. Do not edit: change the knowledge and generate again."];
    for (const line of lines) {
      if (typeof line === "string") text.push(line);
      else if ("label" in line) {
        text.push(line.label);
        labels.push({ address: hex(line.address), name: line.label, file, line: text.length });
      } else {
        text.push(`        ${line.item}`);
        items.push({ start: hex(line.start), end: hex(line.end), file, line: text.length });
      }
    }
    writeFileSync(join(root, "src", file), `${text.join("\n")}\n`);
  }
  writeFileSync(join(root, "src", "source-map.json"), JSON.stringify({ image: "game.prg", space: "c64", revision, files: Object.keys(files), labels, items }));
}

/**
 * A program at $1000: main calls draw, and draw dispatches through an RTS
 * table at $2000 to two handlers; counter at $02 is outside the image; ship is
 * one sprite at $2040, and font is a charset of two characters at $2080.
 */
function project(): { root: string; revision: string } {
  const root = mkdtempSync(join(tmpdir(), "c64-re-tools-docs-"));
  projects.push(root);
  const body = new Uint8Array(0x2090 - 0x1000);
  // The RTS table: handler_a-1 ($101f), handler_b-1 ($1027).
  body.set([0x1f, 0x10, 0x27, 0x10], 0x1000);
  body[0x1040] = 0b1000_0001; // ship: the first row has the first and the eighth pixel
  body[0x1080] = 0b1000_0000; // font: character 0 has its top left pixel
  body[0x108f] = 0b0000_0001; // font: character 1 has its bottom right pixel
  writeFileSync(join(root, "game.prg"), Uint8Array.from([0x00, 0x10, ...body]));
  writeFileSync(
    join(root, "batch.json"),
    JSON.stringify([
      { op: "module", start: "$1000", file: "main_code.asm", title: "Main code" },
      { op: "module", start: "$2000", file: "tables.asm", title: "Tables" },
      { op: "rename", address: "$1000", name: "main", kind: "routine" },
      { op: "rename", address: "$1010", name: "draw", kind: "routine" },
      { op: "rename", address: "$1020", name: "handler_a", kind: "label" },
      { op: "rename", address: "$1028", name: "handler_b", kind: "label" },
      { op: "rename", address: "$2000", name: "handlers", kind: "data" },
      { op: "rename", address: "$2040", name: "ship", kind: "data" },
      { op: "rename", address: "$2080", name: "font", kind: "data" },
      { op: "rename", address: "$0002", name: "counter", kind: "variable" },
      { op: "classify", start: "$1000", end: "$102f", type: "code" },
      { op: "classify", start: "$2000", end: "$2003", type: "rts-addresses" },
      { op: "classify", start: "$2040", end: "$207f", type: "sprite", element: 64 },
      { op: "classify", start: "$2080", end: "$208f", type: "charset" },
      { op: "comment", address: "$1010", placement: "line", text: "Draws the screen." },
      { op: "reference", from: "$1003", to: "$1010", kind: "call" },
      { op: "reference", from: "$1012", to: "$2000", kind: "reference" },
      { op: "reference", from: "$1015", to: "$0002", kind: "write" },
    ]),
  );
  assert.equal(knowledge(root, "apply", "batch.json").status, 0);
  const revision = revisionOf(root);
  writeSource(root, revision, {
    "main_code.asm": [
      "; Main code",
      "; $1000-$102f",
      "",
      { label: "main", address: 0x1000 },
      { item: "jsr draw", start: 0x1000, end: 0x1002 },
      { item: "rts", start: 0x1003, end: 0x1003 },
      "; Draws the screen.",
      { label: "draw", address: 0x1010 },
      { item: "ldx counter", start: 0x1010, end: 0x1011 },
      { item: "lda handlers+1,x", start: 0x1012, end: 0x1014 },
      { item: "sta counter", start: 0x1015, end: 0x1016 },
      { label: "handler_a", address: 0x1020 },
      { item: "rts", start: 0x1020, end: 0x1020 },
      { label: "handler_b", address: 0x1028 },
      { item: "rts", start: 0x1028, end: 0x1028 },
    ],
    "tables.asm": [
      "; Tables",
      "; $2000-$208f",
      "",
      { label: "handlers", address: 0x2000 },
      { item: "!byte <(handler_a-1),<(handler_b-1)", start: 0x2000, end: 0x2003 },
      { label: "ship", address: 0x2040 },
      { item: "!byte %10000001,0,0", start: 0x2040, end: 0x2042 },
      { label: "font", address: 0x2080 },
      { item: "!byte $80,$00,$00,$00,$00,$00,$00,$00", start: 0x2080, end: 0x2087 },
      { item: "!byte $00,$00,$00,$00,$00,$00,$00,$01", start: 0x2088, end: 0x208f },
    ],
    "constants.asm": [{ label: "counter = $02", address: 0x0002 }],
  });
  // The label of a constant is its line "name = value": the map names it by the name only.
  const map = JSON.parse(readFileSync(join(root, "src", "source-map.json"), "utf8")) as { labels: Array<{ name: string }> };
  for (const label of map.labels) label.name = label.name.replace(/ =.*/, "");
  writeFileSync(join(root, "src", "source-map.json"), JSON.stringify(map));
  return { root, revision };
}

test("generate.ts writes the reference: module pages with anchors and links to the lines, tables, variables and graphics", () => {
  const { root, revision } = project();
  const result = generate(root, "--source", "src", "--out", "docs/reference", "--image", "game.prg");
  assert.equal(result.status, 0, JSON.stringify(result.json));
  assert.equal(result.json.revision, revision);
  const read = (page: string) => readFileSync(join(root, "docs/reference", page), "utf8");
  const main = read("modules/main_code.md");
  assert.match(main, /^<!-- Generated by c64-docs from knowledge revision /);
  assert.match(main, /<a id="draw"><\/a>\n### \[`draw`\]\(\.\.\/\.\.\/\.\.\/src\/main_code\.asm#L9\) `\$1010`/);
  assert.match(main, /Draws the screen\./);
  assert.match(main, /- \*\*Called from:\*\* \[`main`\]\(main_code\.md#main\) \[`\$1003`\]\(\.\.\/\.\.\/\.\.\/src\/main_code\.asm#L7\)/);
  assert.match(main, /- \*\*Writes:\*\* \[`counter`\]\(\.\.\/variables\.md#counter\)/);
  // The table entries make edges from the routine that reads the table to each handler.
  assert.match(main, /n1010 ==> n1020\n {2}n1010 ==> n1028/);
  assert.match(main, /- \*\*Entry of:\*\* \[`handlers`\]\(\.\.\/tables\.md#handlers\)/);
  const tables = read("tables.md");
  assert.match(tables, /\| 0 \| \[`\$2000`\]\(\.\.\/\.\.\/src\/tables\.asm#L6\) \| `\$101F` \| \[`handler_a`\]\(\.\.\/\.\.\/src\/main_code\.asm#L13\) \[`\$1020`\]\(modules\/main_code\.md#handler_a\) \|/);
  assert.match(tables, /- \*\*Read by:\*\* \[`draw`\]\(modules\/main_code\.md#draw\) \[`\$1012`\]/);
  assert.match(read("variables.md"), /<a id="counter"><\/a>\n### \[`counter`\]\(\.\.\/\.\.\/src\/constants\.asm#L2\) `\$0002`/);
  assert.match(read("symbols.md"), /\| \[`ship`\]\(\.\.\/\.\.\/src\/tables\.asm#L7\) \| \[`\$2040`\]\(modules\/tables\.md#ship\) \| data \|/);
  const graphics = read("graphics.md");
  assert.match(graphics, /!\[ship in hires\]\(images\/ship-hires\.png\)/);
  const sheet = readPng(readFileSync(join(root, "docs/reference/images/ship-hires.png")));
  // One sprite, 2x2 per pixel, with the gap of one pixel: (24 + 2) x 2 wide.
  assert.equal(sheet.width, 52);
  assert.deepEqual([sheet.pixels[2 * 52 + 2], sheet.pixels[2 * 52 + 4], sheet.pixels[2 * 52 + 16]], [1, 0, 1]);
  assert.match(graphics, /\*charset\*/);
  assert.match(graphics, /!\[font in multicolour\]\(images\/font-multicolour\.png\)/);
  const font = readPng(readFileSync(join(root, "docs/reference/images/font-hires.png")));
  // Two characters side by side, 2x2 per pixel and no gap: 2 x 8 x 2 wide, 8 x 2 high.
  assert.deepEqual([font.width, font.height], [32, 16]);
  assert.deepEqual([font.pixels[0], font.pixels[33], font.pixels[2], font.pixels[15 * 32 + 31], font.pixels[15 * 32 + 29]], [1, 1, 0, 1, 0]);
  assert.match(read("index.md"), /\| \[main_code\.asm\]\(modules\/main_code\.md\) \| `\$1000-\$1028` \| Main code \| 4 \| 4 \|/);
});

test("generate.ts refuses a page of a person in the output directory and a source of another revision", () => {
  const { root } = project();
  mkdirSync(join(root, "docs/reference"), { recursive: true });
  writeFileSync(join(root, "docs/reference/notes.md"), "# My notes\n");
  const refused = generate(root, "--source", "src", "--out", "docs/reference");
  assert.equal(refused.status, 1);
  assert.match(String((refused.json.error as { message: string }).message), /docs\/reference\/notes\.md is not a page of generate\.ts/);
  rmSync(join(root, "docs/reference/notes.md"));
  // An earlier run's pages go; the run writes them again.
  assert.equal(generate(root, "--source", "src", "--out", "docs/reference").status, 0);
  writeFileSync(join(root, "docs/reference/modules/old.md"), "<!-- Generated by c64-docs from knowledge revision 0 -->\n");
  assert.equal(generate(root, "--source", "src", "--out", "docs/reference").status, 0);
  assert.equal(existsSync(join(root, "docs/reference/modules/old.md")), false);

  knowledge(root, "rename", "$1028", "handler_two");
  const stale = generate(root, "--source", "src", "--out", "docs/reference");
  assert.equal(stale.status, 1);
  assert.match(String((stale.json.error as { message: string }).message), /Generate the source again with c64-source/);
  assert.equal(generate(root, "--source", "missing", "--out", "docs/reference").status, 1);
  assert.equal(generate(root, "--out", "docs/reference").status, 2);
});

