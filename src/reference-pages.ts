// The first line of each reference page that c64-docs generates: it names
// the knowledge revision and the source map that the page was made from. The
// docs script writes and checks it; the generation of the source reads it to
// tell when a reference of the project is older than the source.

import { closeSync, openSync, readdirSync, readSync } from "node:fs";
import { join, posix } from "node:path";

/** The start of every generated page. A page without it is a page of a person, and the generation never writes over it. */
export const GENERATED_MARK = "<!-- Generated by c64-docs";

/** The first line of a generated page: the knowledge revision and the source map of the source that it was made from. */
export function referenceHeader(revision: string, mapPath: string): string {
  return `${GENERATED_MARK} from knowledge revision ${revision} and ${mapPath}. Do not edit: change the knowledge, generate the source again, then run docs.ts generate. -->`;
}

const STAMP = /^<!-- Generated by c64-docs from knowledge revision (\S+) and (.+?)\. Do not edit/;

/** The revision and the source map that a generated page names, or undefined for a page of a person. */
export function referenceStamp(text: string): { revision: string; mapPath: string } | undefined {
  const found = STAMP.exec(text);
  return found === null ? undefined : { revision: found[1]!, mapPath: posix.normalize(found[2]!) };
}

/** The first bytes of a file: enough for the first line of a page. */
function head(path: string): string {
  const descriptor = openSync(path, "r");
  try {
    const buffer = Buffer.alloc(512);
    return buffer.subarray(0, readSync(descriptor, buffer, 0, buffer.length, 0)).toString("utf8");
  } catch {
    return "";
  } finally {
    closeSync(descriptor);
  }
}

/**
 * The generated references in a project folder: each folder with a
 * generated index.md, relative to the project with /, and the revision and
 * source map of its index. Folders that start with a dot are not searched.
 */
export function generatedReferences(root: string): Array<{ folder: string; revision: string; mapPath: string }> {
  const found: Array<{ folder: string; revision: string; mapPath: string }> = [];
  const walk = (relative: string) => {
    let entries;
    try {
      entries = readdirSync(join(root, relative), { withFileTypes: true });
    } catch {
      return;
    }
    for (const entry of entries.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))) {
      if (entry.name.startsWith(".") || entry.name === "node_modules") continue;
      const path = posix.join(relative, entry.name);
      if (entry.isDirectory()) walk(path);
      else if (entry.isFile() && entry.name === "index.md") {
        const stamp = referenceStamp(head(join(root, path)));
        if (stamp !== undefined) found.push({ folder: relative === "" ? "." : relative, ...stamp });
      }
    }
  };
  walk("");
  return found;
}
