#!/usr/bin/env node
// src/mcp/vice/fixtures/harness-signal/plant-contract-driver.mjs
//
// WHY THIS FILE EXISTS: `WR-36` records that three of the mutation harness's
// behaviours ship with NO standing coverage at all -- the plant post-condition
// arithmetic, the SKIPPED reporting and the refused-plant reporting -- proven
// only by one-off manual runs. Its three sibling drivers here all exercise the
// RESTORE machinery; not one of them exercises the PLANT CONTRACT: what
// `plant()` accepts, what it refuses, and whether the bytes it writes are the
// bytes the descriptor records.
//
// That gap is not academic. Gap 1 of this phase's round-3 verification is a real
// committed evidence row -- `src/mcp/vice/hop-chain-comments.test.ts` -- whose
// HONEST descriptor the post-condition refused, because the arithmetic computed
// the introduction of the recorded replacement as a whole-file difference
// (count after minus count before) and that subtraction cannot see a
// replacement which textually OVERLAPS its own pre-existing occurrence. One
// refused plant sets the row's failed flag, which sets the run's hard-failure
// flag, which suppresses the whole-set registry write-back -- so the artefact at
// the centre of `CUT-04` could not be regenerated by its own `--all` command
// while that row stood.
//
// So this driver states the plant contract as a set of NAMED CASES and reports
// what actually happened, one case per process:
//
//   1. IMPORT the harness. Its `IS_ENTRY_POINT` guard keeps `main()` from
//      running on import, so importing it reads no registry, spawns no guard and
//      writes no evidence file. (It does register the four process handlers at
//      module scope -- see the placement note at the foot of this header.)
//   2. WRITE a throwaway target into a caller-supplied scratch root, shaped for
//      the one named case this invocation was asked to run.
//   3. READ and keep the pre-plant bytes.
//   4. BUILD a row object in code with a worktree plant descriptor -- never a
//      real registry row.
//   5. CALL the harness's exported `plant()` inside a try/catch.
//   6. RE-READ the target and print ONE JSON verdict line carrying the case
//      name, whether the plant succeeded or was refused, the refusal message
//      VERBATIM when there was one, whether the target is byte-identical to its
//      pre-plant bytes, the length before and after, the bytes read back from
//      the match position, and the value `pendingRestoreCount()` returns.
//
// ONE CASE PER INVOCATION, DELIBERATELY. The parent spawns a separate child with
// its own scratch root for every case, so a case that throws, hangs or corrupts
// its target can never mask another one, and no case inherits another's
// captured-originals map. A single child running every case would report the
// first failure and hide the rest -- which is the reporting defect gap 1 is
// itself an instance of.
//
// EXIT STATUS MEANS "DID I OBSERVE", NOT "DID IT PASS". This driver exits 0
// whenever it completed its observation, including when the plant was REFUSED --
// a refusal is an observation, and several cases below expect one. It exits
// non-zero only when it could not make an observation at all (bad arguments, an
// unknown case name, an unexpected throw outside `plant()`). The parent asserts
// on the JSON verdict rather than on the exit status.
//
// WHAT NOT TO DO:
//
//   - Do NOT "fix" the harness from here if a case comes back with an unexpected
//     outcome. That outcome is a FINDING to record, not a defect to repair
//     inside a fixture -- the same standing rule `restore-latch-driver.mjs`
//     carries. This driver measures the plant contract; it does not change it.
//   - Do NOT call `main()`, `runGuard()` or any sweep entry point, and do not
//     pass a real registry row. No registry is read, no guard is spawned, no
//     member of the audited set runs, no evidence file is written.
//   - Do NOT register a signal handler here, and do not call `restoreAll()`.
//     A successful plant is left for the harness's own registered `exit` handler
//     to restore on the way out -- which is also why the verdict reports
//     `pendingRestoreCount()` as 1 after an accepted plant and must report 0
//     after a refused one.
//   - Do NOT reach into the harness's internal map. The pending count comes from
//     the exported `pendingRestoreCount()` accessor, which returns the map's
//     size and nothing else, so this driver can observe the machinery without
//     acquiring the ability to mutate it.
//   - Do NOT reuse one scratch root across cases, and do not write outside the
//     scratch root the caller supplied.
//
// Like all three siblings this file lives under `fixtures/` deliberately:
// `test-gate.mjs`'s `automatedTestFiles()` uses a NON-RECURSIVE `readdirSync`,
// so nothing here is ever collected as a test in its own right. That matters
// more than tidiness -- importing this module registers a SIGINT handler that
// calls `process.exit(130)`, which must never happen inside the test runner.

import { writeFileSync, readFileSync } from "node:fs";
import { join } from "node:path";

import { plant, pendingRestoreCount } from "../../../../../scripts/audit-mutation-harness.mjs";

const TARGET_NAME = "plant-contract-target.txt";

/**
 * The same deliberately non-UTF-8 tail all three sibling drivers use: `0x00` and
 * the lone `0xFF 0xFE 0x80` bytes have no UTF-8 interpretation and `0xC3 0x28`
 * is a truncated two-byte sequence, so decoding any of them as UTF-8 and
 * re-encoding yields U+FFFD (`EF BF BD`) instead. Every byte comparison the
 * parent makes is therefore a byte comparison in the strong sense: a merely
 * text-equal write through a different encoding fails it.
 */
const BINARY_TAIL = Buffer.from([0x00, 0xff, 0xfe, 0x80, 0xc3, 0x28]);

/** The overlap anchor. Sits on its own line, so the string `"\n" + ANCHOR`
 * ALREADY occurs exactly once in the target before any mutation -- which is what
 * makes the introduced occurrence textually overlap the pre-existing one. */
const ANCHOR = "HARNESS_PLANT_CONTRACT_ANCHOR";

const FIND_B = "HARNESS_PLANT_CONTRACT_FIND_B";
const REPLACE_B = "HARNESS_PLANT_CONTRACT_REPLACE_B";

const FIND_C = "HARNESS_PLANT_CONTRACT_FIND_C";
/** Carries `$&`, which `String.prototype.replace` expands to the matched
 * substring when it is given a replacement STRING. A replacer FUNCTION returns
 * it verbatim. That difference is the whole of the `CR-02` fix, and this case is
 * the standing pin on it. */
const REPLACE_C = "HARNESS_PLANT_CONTRACT_C_$&_TAIL";

const FIND_TWICE = "HARNESS_PLANT_CONTRACT_TWICE";
const FIND_ABSENT = "HARNESS_PLANT_CONTRACT_ABSENT_FIND";
const FIND_D = "HARNESS_PLANT_CONTRACT_FIND_D";

/**
 * Every case this driver knows how to run. `lines` are written after a fixed
 * header line and before the binary tail, so any string named in `lines` is
 * preceded by a newline -- which is what the overlap case depends on.
 */
const CASES = {
  // ---- accepted ---------------------------------------------------------
  "overlap-accepted": {
    lines: [ANCHOR],
    find: ANCHOR,
    replace: `\n${ANCHOR}`,
  },
  "pre-existing-replacement-accepted": {
    lines: [REPLACE_B, FIND_B],
    find: FIND_B,
    replace: REPLACE_B,
  },
  "substitution-is-verbatim": {
    lines: [FIND_C],
    find: FIND_C,
    replace: REPLACE_C,
  },

  // ---- refused ----------------------------------------------------------
  "find-absent-refused": {
    lines: [ANCHOR],
    find: FIND_ABSENT,
    replace: "HARNESS_PLANT_CONTRACT_ABSENT_REPLACE",
  },
  "find-twice-refused": {
    lines: [FIND_TWICE, FIND_TWICE],
    find: FIND_TWICE,
    replace: "HARNESS_PLANT_CONTRACT_TWICE_REPLACE",
  },
  "empty-replacement-refused": {
    lines: [FIND_D],
    find: FIND_D,
    replace: "",
  },
};

function targetBytes(lines) {
  return Buffer.concat([
    Buffer.from("// harness plant-contract target, written by the driver\n", "latin1"),
    Buffer.from(lines.map((l) => `${l}\n`).join(""), "latin1"),
    BINARY_TAIL,
    Buffer.from("\n// end of target\n", "latin1"),
  ]);
}

function main() {
  const scratchRoot = process.argv[2];
  const caseName = process.argv[3];
  if (typeof scratchRoot !== "string" || scratchRoot.length === 0) {
    process.stderr.write("plant-contract-driver: usage: <scratch-root> <case-name>\n");
    process.exit(2);
  }
  if (typeof caseName !== "string" || !Object.hasOwn(CASES, caseName)) {
    process.stderr.write(
      `plant-contract-driver: unknown case ${JSON.stringify(caseName)}. Known cases: ` +
        `${Object.keys(CASES).join(", ")}\n`,
    );
    process.exit(2);
  }

  const spec = CASES[caseName];
  const absTarget = join(scratchRoot, TARGET_NAME);
  writeFileSync(absTarget, targetBytes(spec.lines));
  const original = readFileSync(absTarget);
  const originalText = original.toString("latin1");

  const descriptor = {
    kind: "worktree",
    file: spec.file ?? TARGET_NAME,
    find: spec.find,
    replace: spec.replace,
  };
  const row = {
    historicalPath: "fixtures/harness-signal/plant-contract-driver.mjs",
    plant: descriptor,
  };

  // Taken from the PRE-MUTATION text, with the literal index-of operation and
  // never a regular expression, so it is the same unique position the harness's
  // own post-condition binds. `-1` (find absent) is reported as `null` rather
  // than folded into a position.
  const rawMatchIndex = originalText.indexOf(spec.find);
  const matchIndex = rawMatchIndex < 0 ? null : rawMatchIndex;

  let planted = false;
  let refusalMessage = null;
  try {
    plant(scratchRoot, row);
    planted = true;
  } catch (err) {
    refusalMessage = err?.message ?? String(err);
  }

  const after = readFileSync(absTarget);
  const afterText = after.toString("latin1");

  // The bytes the WRITE PATH would produce for the recorded replacement, and the
  // bytes actually sitting at the match position afterwards. On an accepted
  // plant of a faithfully-writable descriptor these are equal; a divergence
  // between them is the harness writing bytes the row does not record.
  const recordedReplacementBytes = Buffer.from(spec.replace, "latin1");
  const bytesAtMatchIndex =
    matchIndex === null
      ? null
      : after.subarray(matchIndex, matchIndex + recordedReplacementBytes.length);

  const verdict = {
    case: caseName,
    planted,
    refusalMessage,
    targetByteIdentical: after.equals(original),
    lengthBefore: original.length,
    lengthAfter: after.length,
    lengthDelta: after.length - original.length,
    /** String-level, the same quantity the corrected post-condition expects. */
    expectedDelta: spec.replace.length - spec.find.length,
    matchIndex,
    /** Measured on the FILE, not on an in-memory string: this is the fact a
     * string-level check inside the harness cannot see being violated. */
    replacementVerbatimAtMatchIndex:
      matchIndex !== null && afterText.startsWith(spec.replace, matchIndex),
    bytesAtMatchIndexBase64: bytesAtMatchIndex === null ? null : bytesAtMatchIndex.toString("base64"),
    recordedReplacementBase64: recordedReplacementBytes.toString("base64"),
    originalBase64: original.toString("base64"),
    afterBase64: after.toString("base64"),
    pendingRestoreCount: pendingRestoreCount(),
  };

  process.stdout.write(`${JSON.stringify(verdict)}\n`);
}

main();
