// The packed loader program of a generated source: the ranges that it loads,
// the check of the two builds before the pack, and the symbols of a loader
// program. The pack with Exomizer is in test/skills/c64-source.test.ts.

import assert from "node:assert/strict";
import { test } from "node:test";

import { Refusal } from "./errors.ts";
import { checkPackedBuilds, leftoverRange, loaderSymbols, packedRanges } from "./loader.ts";

const prg = (start: number, bytes: number[]) => Uint8Array.from([start & 0xff, start >> 8, ...bytes]);
const refused = (pattern: RegExp) => (error: unknown) => error instanceof Refusal && error.code === "invalid-input" && pattern.test(error.message);

test("the packed loader loads the segments without the leftovers, and refuses a start screen of a stage and a segment below $0400", () => {
  const leftover = leftoverRange("; Generated by c64-source.\n; Leftovers $1010-$105f: 80 bytes that nothing uses. Only LEFTOVERS = 1 builds them.\n");
  assert.deepEqual(leftover, { start: 0x1010, end: 0x105f });
  assert.equal(leftoverRange("; my notes\n"), undefined);
  assert.deepEqual(packedRanges([{ start: 0x2000, end: 0x2003 }, { start: 0x1000, end: 0x10ff }], [leftover!], undefined), [
    { start: 0x1000, end: 0x100f },
    { start: 0x1060, end: 0x10ff },
    { start: 0x2000, end: 0x2003 },
  ]);
  assert.throws(() => packedRanges([{ start: 0x1000, end: 0x10ff }], [], "loading"), refused(/^The start screen is of the captured stage loading, and only the generation of the source with the loader makes that loader program\./));
  assert.throws(() => packedRanges([{ start: 0x0300, end: 0x10ff }], [], undefined), refused(/^The segment \$0300-\$10ff starts below \$0400, /));
});

test("the build of loader.asm must hold the bytes of the build of main.asm between its free ranges, and main.asm must hold each loaded range", () => {
  // The copier build spans $c000-$c00f; the loaded range $c004-$c007 is between its free ranges.
  const main = prg(0xc004, [1, 2, 3, 4]);
  const copier = prg(0xc000, [0xea, 0xea, 0xea, 0xea, 1, 2, 3, 4, 0xea, 0xea, 0xea, 0xea, 0xea, 0xea, 0xea, 0xea]);
  checkPackedBuilds(main, copier, [{ start: 0xc004, end: 0xc007 }]);
  // A switch that patches $c006 in main.asm: loader.asm still holds the byte of generate.
  assert.throws(() => checkPackedBuilds(prg(0xc004, [1, 2, 9, 4]), copier, [{ start: 0xc004, end: 0xc007 }]), refused(/^These switch values change the byte at \$c006, between the free ranges of loader\.asm \(\$c000-\$c00f\)/));
  assert.throws(() => checkPackedBuilds(main, copier, [{ start: 0xc004, end: 0xc008 }]), refused(/^The build of main\.asm does not hold \$c004-\$c008 of the program in the knowledge\./));
});

test("the symbols of the loader program hold the labels of both builds, and refuse a name with two values", () => {
  const merged = loaderSymbols(
    [{ name: "main", kind: "address", address: 0x0810, used: true }, { name: "START_SCREEN", kind: "constant", value: 1, used: false }, { name: "game_start", kind: "constant", value: 0xc000, used: false }],
    [{ name: "loader_start_screen_wait", kind: "address", address: 0xc123, used: true }, { name: "START_SCREEN", kind: "constant", value: 1, used: true }, { name: "game_start", kind: "address", address: 0xc000, used: false }],
  );
  assert.deepEqual(merged.map((symbol) => [symbol.name, symbol.kind, symbol.used]), [["START_SCREEN", "constant", true], ["game_start", "address", false], ["loader_start_screen_wait", "address", true], ["main", "address", true]]);
  assert.throws(() => loaderSymbols([{ name: "main", kind: "address", address: 0x0810, used: true }], [{ name: "main", kind: "address", address: 0x0820, used: true }]), /give main two values, 2064 and 2080/);
});
