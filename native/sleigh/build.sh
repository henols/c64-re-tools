#!/usr/bin/env bash
# Builds src/native/ghidra/c64rt-wasm.ts: the Ghidra SLEIGH and decompiler port
# (ghidra-decompiler 2.1.0 from crates.io, with ghidra-decompiler.patch) and
# the c64-re-tools 6510 language, as WebAssembly in a base64 string (a skill
# installs its files as text). Run by hand when this crate, the patch or the
# language changes; the result is committed.
set -euo pipefail
cd "$(dirname "$0")"

VERSION=2.1.0
SHA256=a68a5bd2d6e7f477e4e9cd41f3ebcd7d2e43e30775c2fd620c05786f60c60a92
CRATE=target/ghidra-decompiler-$VERSION

mkdir -p target
if [ ! -f "$CRATE/.patched" ]; then
  rm -rf "$CRATE"
  curl -fsSL -o target/ghidra-decompiler.crate "https://static.crates.io/crates/ghidra-decompiler/ghidra-decompiler-$VERSION.crate"
  echo "$SHA256  target/ghidra-decompiler.crate" | sha256sum -c -
  tar -xzf target/ghidra-decompiler.crate -C target
  patch -d "$CRATE" -p1 < ghidra-decompiler.patch
  touch "$CRATE/.patched"
fi

# The build needs a few GB; a cap keeps a runaway link from taking the desktop down.
run=()
if command -v systemd-run >/dev/null && systemd-run --user --scope -q true 2>/dev/null; then
  run=(systemd-run --user --scope -q -p MemoryMax=8G -p MemorySwapMax=0)
fi
"${run[@]}" cargo build -j 4 --release --locked --target wasm32-unknown-unknown

WASM=target/wasm32-unknown-unknown/release/c64rt_sleigh.wasm
OUT=../../src/native/ghidra/c64rt-wasm.ts
{
  echo "// Generated by native/sleigh/build.sh: do not edit."
  echo "// The WebAssembly module, base64. SHA-256 $(sha256sum "$WASM" | cut -d' ' -f1)."
  echo "export const C64RT_WASM ="
  echo "  \"$(base64 -w0 "$WASM")\";"
} > "$OUT"
sha256sum "$WASM"
