#!/usr/bin/env node
// check-no-skill-external-spawn.mjs
//
// SEAM-05's closing gate: no skill script may reach a host binary through a
// direct child-process call. Phase 34 migrated the two skill scripts that
// used to do this (`acme.mjs`, `packer-finding.mjs`, plan 34-04) onto the
// host-tool execution seam (`src/mcp/vice/host-tool.mts`'s typed allowlist).
// This file is what keeps that migration permanent rather than a one-time
// cleanup a future skill script can quietly undo -- see BANNED_COMMAND_SHAPES
// below for exactly what is forbidden; this header deliberately does not
// restate every entry in one re-quotable sentence (check-npm-packages.mjs's
// own naming discretion, :127-133).
//
// SCOPE, AND WHY IT IS TWO ROUTES, NEVER `git ls-files` ALONE: a skill
// script reaches a user through TWO independent packaging routes -- the
// `@henols/c64-re-tools` npm tarball (built from `installer/skills/`, a
// directory this repository's own `.gitignore` excludes, regenerated by the
// installer's own `prepack` hook from `src/skills/` on every pack) and the
// Claude Code PLUGIN route, which ships `src/skills/` directly from the git
// tree. A scope that only reads the git-tracked tree would be green on a
// perfectly clean commit while the SHIPPED tarball still carried a stale,
// violating copy synced in from a moment before the fix -- the exact
// direction `.planning/ROADMAP.md`'s own Standing Constraint on this phase
// names as the worst one: the tracked copy is correct, the gate is green,
// and the shipped copy is wrong. `skillScriptFilesFromPackedTarball()` below
// reuses `check-npm-packages.mjs`'s own `packFiles()` -- never a
// re-implementation of `npm pack --dry-run --json` -- specifically because
// THAT function runs the installer's `prepack` hook first, so the file list
// it returns is post-sync BY CONSTRUCTION and cannot forget to sync.
//
// CONCURRENCY (stated once, here, because nothing else states it): calling
// `skillScriptFilesFromPackedTarball()` re-runs the installer's `prepack`
// hook -- and therefore its skill-sync -- every time. Do not run this script,
// or import its packed-tarball route, concurrently with another caller of
// `packFiles()` (today: `check-npm-packages.mjs`'s own driver and
// `scripts/package.sh`); a second sync racing the first can observe a
// partially-rewritten `installer/skills/` tree.
//
// THE INTERPRETER EXEMPTION, the gate's hardest case: `vsf-slice.mjs` spawns
// `process.execPath` (the interpreter already running IT) on a module inside
// one of this project's own two npm packages -- not an external host binary,
// and not a case this gate exists to catch. `skillScriptSpawnViolations()`
// exempts a call whose command resolves to the running interpreter, directly
// or through a local variable declared from it, and `vsf-slice.mjs` stays in
// both scopes specifically so that exemption is proven against a real file
// rather than only a synthetic one (see the companion test).
//
// DISCIPLINE: no allowlist of permitted violating files exists in this file
// and none should be added. After Phase 34's migration the discovered set is
// exactly empty; an entry added later to make a red run green again is
// precisely the decay pattern `.planning/ROADMAP.md`'s Standing Constraint on
// repaired guards describes.
//
// Structured as ONE exported pure predicate (`skillScriptSpawnViolations`)
// plus TWO exported scope enumerators plus a driver guarded on being the
// process entry point -- `check-npm-packages.mjs`'s own `IS_ENTRY_POINT`
// idiom, so this gate's test can import the predicate without running the
// driver, and importing `packFiles()` here does not trigger THAT script's
// own driver either.
import { readFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { dirname, join, resolve } from "node:path";

import { packFiles } from "./check-npm-packages.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = dirname(HERE);

/** The external host binaries a skill script must never reach directly.
 * Frozen, and deliberately never widened into an allowlist of EXCEPTIONS --
 * every name here is something to REFUSE, not something to permit. Covers:
 * the assembler, the packer-identifier oracle's two documented names (its
 * default command and its primary env-var-derived name), the future
 * disassembly/discovery seam consumer, the Ghidra headless launcher, the
 * three VICE utilities named as future seam consumers, and the emulator
 * binary itself -- so this gate and `spawn-seam.test.ts` agree a skill
 * script must never spawn it either. */
export const BANNED_COMMAND_SHAPES = Object.freeze([
  "acme",
  "unp64",
  "UNP64",
  "dxa",
  "analyzeHeadless",
  "c1541",
  "petcat",
  "cartconv",
  "x64sc",
]);

const ARGV_SPAWN_NAMES = ["spawnSync", "spawn", "execFileSync", "execFile"];
const SHELL_SPAWN_NAMES = ["execSync", "exec"];

function escapeRegExp(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

/** Strip `//` and `/* *\/` comments while leaving every string/template
 * literal body untouched -- deliberately the OPPOSITE trade-off from
 * `shipped-modules.ts`'s `codeOnly()` default. This gate's own violation
 * shape can live inside a literal's text (a bare command-name string passed
 * as a spawn call's first argument), so blanking literal bodies would make
 * the violation unobservable. Comments ARE stripped, because a comment
 * mentioning a banned name in prose -- this file's OWN header does exactly
 * that -- must never itself read as a call site. */
function stripComments(src) {
  let out = "";
  const n = src.length;
  let i = 0;
  while (i < n) {
    const c = src[i];
    const c2 = i + 1 < n ? src[i + 1] : "";
    if (c === "/" && c2 === "/") {
      while (i < n && src[i] !== "\n") i++;
      continue;
    }
    if (c === "/" && c2 === "*") {
      i += 2;
      while (i < n && !(src[i] === "*" && src[i + 1] === "/")) i++;
      i = Math.min(i + 2, n);
      continue;
    }
    if (c === '"' || c === "'" || c === "`") {
      const quote = c;
      out += c;
      i++;
      while (i < n && src[i] !== quote) {
        if (src[i] === "\\" && i + 1 < n) {
          out += src[i] + src[i + 1];
          i += 2;
          continue;
        }
        out += src[i];
        i++;
      }
      if (i < n) {
        out += src[i];
        i++;
      }
      continue;
    }
    out += c;
    i++;
  }
  return out;
}

/** Second pass over `stripped` (comments already removed): blank every
 * string/template-literal BODY to a same-length run of `#`, preserving every
 * other character (and therefore every index) exactly. This is used ONLY to
 * locate genuine call-site syntax -- a banned name that exists ONLY inside a
 * string that is not a call's first argument (this gate's own false-positive
 * control) must never be discoverable as a call at all, and blanking the
 * string body is what removes it from the scan without disturbing any other
 * position. The REAL argument text is always read back from `stripped`
 * (never from this blanked copy) once a call site's position is known. */
function blankStrings(stripped) {
  let out = "";
  const n = stripped.length;
  let i = 0;
  while (i < n) {
    const c = stripped[i];
    if (c === '"' || c === "'" || c === "`") {
      const quote = c;
      out += "#";
      i++;
      while (i < n && stripped[i] !== quote) {
        if (stripped[i] === "\\" && i + 1 < n) {
          out += "##";
          i += 2;
          continue;
        }
        out += "#";
        i++;
      }
      if (i < n) {
        out += "#";
        i++;
      }
      continue;
    }
    out += c;
    i++;
  }
  return out;
}

function isQuotedLiteral(token) {
  return /^(["']).*\1$/.test(token);
}

function literalValue(token) {
  return token.slice(1, -1);
}

/** True iff `name` (one of BANNED_COMMAND_SHAPES) appears in `text` as a
 * standalone word -- never as a substring of a longer identifier. */
function textNamesCommand(text, name) {
  const re = new RegExp(`(^|[^A-Za-z0-9_$])${escapeRegExp(name)}([^A-Za-z0-9_$]|$)`);
  return re.test(text);
}

/** The first BANNED_COMMAND_SHAPES entry found as a standalone word in
 * `text`, or `null`. */
function bannedNameIn(text) {
  for (const name of BANNED_COMMAND_SHAPES) {
    if (textNamesCommand(text, name)) return name;
  }
  return null;
}

/** True iff `token` -- an argv-form call's first-argument text, exactly as
 * captured from real (unblanked) source -- resolves to the interpreter
 * already running the script: `process.execPath` directly, or a local
 * variable whose OWN declaration mentions `process.execPath`. */
function resolvesToInterpreter(token, stripped) {
  const trimmed = token.trim();
  if (/^process\.execPath$/.test(trimmed)) return true;
  if (isQuotedLiteral(trimmed)) return false;
  const ident = trimmed;
  if (!/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(ident)) return false;
  const declRe = new RegExp(`\\b(?:const|let|var)\\s+${ident}\\b[^=]*=\\s*([^;\\n]*)`, "g");
  for (const m of stripped.matchAll(declRe)) {
    if (/\bprocess\.execPath\b/.test(m[1])) return true;
  }
  return false;
}

/** The BANNED_COMMAND_SHAPES entry `token` resolves to, or `null`: a
 * matching quoted literal directly, or -- for a bare identifier -- a
 * matching name mentioned in that identifier's OWN declaration. */
function resolvedBannedName(token, stripped) {
  const trimmed = token.trim();
  if (isQuotedLiteral(trimmed)) {
    const value = literalValue(trimmed);
    return BANNED_COMMAND_SHAPES.includes(value) ? value : null;
  }
  const ident = trimmed;
  if (!/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(ident)) return null;
  const declRe = new RegExp(`\\b(?:const|let|var)\\s+${ident}\\b[^=]*=\\s*([^;\\n]*)`, "g");
  for (const m of stripped.matchAll(declRe)) {
    const found = bannedNameIn(m[1]);
    if (found) return found;
  }
  return null;
}

/** Extracts the FIRST argument's raw text starting at `startIdx` in
 * `stripped` -- either a quoted string literal (kept WITH its quotes, so
 * `isQuotedLiteral()` can recognise it) or a dotted identifier chain
 * (`foo`, `process.execPath`). Returns `null` if neither shape is found
 * (e.g. the first argument is itself a nested call or object literal --
 * out of this gate's scope; a skill script naming a banned binary through
 * such a shape is not a pattern any migrated or real script uses today). */
function extractFirstArgToken(stripped, startIdx) {
  const rest = stripped.slice(startIdx);
  const quoted = rest.match(/^"(?:[^"\\]|\\.)*"|^'(?:[^'\\]|\\.)*'/);
  if (quoted) return quoted[0];
  const ident = rest.match(/^[A-Za-z_$][A-Za-z0-9_$]*(?:\.[A-Za-z_$][A-Za-z0-9_$]*)*/);
  if (ident) return ident[0];
  return null;
}

/** Every argv-form spawn call site in `stripped`, located via `blanked` so a
 * call spelled out inside a STRING (this gate's own decoy control) is never
 * discovered -- its text is all blanked to `#` there and cannot match
 * `\b(spawnSync|...)\b`. The real first-argument text is then read back from
 * `stripped` at the same offset, since blanking preserves length and every
 * non-string character exactly. */
function findArgvCallSites(stripped, blanked) {
  const sites = [];
  const scanRe = new RegExp(`\\b(${ARGV_SPAWN_NAMES.join("|")})\\s*\\(\\s*`, "g");
  for (const m of blanked.matchAll(scanRe)) {
    const idx = m.index ?? -1;
    if (idx < 0) continue;
    const afterIdx = idx + m[0].length;
    const arg = extractFirstArgToken(stripped, afterIdx);
    if (arg !== null) sites.push({ fn: m[1], arg, index: idx });
  }
  return sites;
}

/** Every shell-form spawn call site (`execSync`/`exec`), same
 * blanked-then-real-source technique as the argv form. The lookbehind
 * `(?<![.\w$])` is the SAME one `spawn-seam.test.ts` uses for the identical
 * reason: it is what keeps a bare `RegExp.prototype.exec(...)` call --
 * ubiquitous in this codebase's own guards -- from ever being mistaken for a
 * shell spawn. The captured argument text runs to the end of the source
 * line (or 200 characters, whichever is shorter), which is enough to see an
 * interpolated `${identifier}` or an inline banned-name substring without
 * needing a real parser for argument-boundary detection. */
function findShellCallSites(stripped, blanked) {
  const sites = [];
  const scanRe = new RegExp(`(?<![.\\w$])(${SHELL_SPAWN_NAMES.join("|")})\\s*\\(\\s*`, "g");
  for (const m of blanked.matchAll(scanRe)) {
    const idx = m.index ?? -1;
    if (idx < 0) continue;
    const afterIdx = idx + m[0].length;
    const lineEnd = stripped.indexOf("\n", afterIdx);
    const cap = lineEnd === -1 ? afterIdx + 200 : Math.min(lineEnd, afterIdx + 200);
    sites.push({ fn: m[1], arg: stripped.slice(afterIdx, cap), index: idx });
  }
  return sites;
}

/** Distinguishing marker so a caller can tell "empty scope, refused" apart
 * from "scanned everything, found nothing" via `Array.isArray()` -- an empty
 * ARRAY is a real, meaningful verdict (a clean tree); this is not one. */
function nonVacuityFailure() {
  return Object.freeze({
    nonVacuityFailure: true,
    message:
      "skillScriptSpawnViolations() was called with an empty file list -- refusing to report an " +
      "empty violation list for an empty scope (a broken glob or a wrong root must FAIL loudly, " +
      "never read as OK)",
  });
}

/**
 * The ONE named predicate the real scan and every planted violation in the
 * companion test both call. `files` is a list of `{ name, source }` records
 * (never read from disk by this function -- no filesystem or process access
 * happens here at all, so two calls over the same input always agree).
 *
 * Returns a SORTED array of `{ file, fn, command, reason }` violation
 * records -- possibly empty, meaning a clean scan -- or the distinguished
 * `nonVacuityFailure()` marker when `files` itself is empty.
 */
export function skillScriptSpawnViolations(files) {
  if (!Array.isArray(files) || files.length === 0) return nonVacuityFailure();

  const violations = [];
  for (const file of files) {
    const { name, source } = file;
    const stripped = stripComments(source);
    const blanked = blankStrings(stripped);

    for (const site of findArgvCallSites(stripped, blanked)) {
      if (resolvesToInterpreter(site.arg, stripped)) continue;
      const command = resolvedBannedName(site.arg, stripped);
      if (command) {
        violations.push({
          file: name,
          fn: site.fn,
          command,
          reason: "argv-form call names a banned host binary as its command",
        });
      }
    }

    for (const site of findShellCallSites(stripped, blanked)) {
      const interpolated = [...site.arg.matchAll(/\$\{([^}]+)\}/g)].map((m) => m[1].trim());
      const inlineBanned = bannedNameIn(site.arg);
      const interpolatedBanned = interpolated
        .map((ident) => resolvedBannedName(ident, stripped))
        .find((v) => v);
      const command = inlineBanned ?? interpolatedBanned ?? null;
      if (command) {
        violations.push({
          file: name,
          fn: site.fn,
          command,
          reason: "shell-form call interpolates a banned command into a command string",
        });
        continue;
      }
      // Exemption is only relevant once we know there is no banned name at
      // all -- an interpolated interpreter reference alongside a banned name
      // would already have been reported above and must stay reported.
    }
  }

  violations.sort(
    (a, b) =>
      a.file.localeCompare(b.file) ||
      a.command.localeCompare(b.command) ||
      a.fn.localeCompare(b.fn) ||
      a.reason.localeCompare(b.reason),
  );
  return violations;
}

/**
 * The skill-script records the `@henols/c64-re-tools` tarball actually
 * contains, obtained through `packFiles()` so the list is post-`prepack` --
 * this is the route that sees what a user receives, including the
 * gitignored-but-shipped `installer/skills/` copy. Filters to the skills
 * tree's own `.mjs` entries, excluding `*.test.mjs` (test files never ship
 * and are not this gate's subject either way).
 */
export function skillScriptFilesFromPackedTarball(installerDir = join(ROOT, "installer")) {
  const packed = packFiles(installerDir);
  const records = [];
  for (const relPath of packed.files) {
    if (!relPath.startsWith("skills/")) continue;
    if (!relPath.endsWith(".mjs")) continue;
    if (relPath.endsWith(".test.mjs")) continue;
    const source = readFileSync(join(installerDir, relPath), "utf8");
    records.push({ name: relPath, source });
  }
  return records.sort((a, b) => a.name.localeCompare(b.name));
}

/**
 * The git-tracked `src/skills/*<skill>/scripts/*.mjs` records for the
 * plugin route, which ships `src/skills/` directly rather than through a
 * packed tarball. Enumerated via `git ls-files` (never a raw `readdirSync`,
 * which would also see untracked scratch files) and read with `readFileSync`
 * directly -- a binary-safe read by construction, unlike a `grep` without
 * `-a`, which would silently skip a source file containing a NUL byte (a
 * failure mode this project has already made one wrong decision from).
 */
export function skillScriptFilesFromTrackedTree(repoRoot = ROOT) {
  const listing = execFileSync("git", ["ls-files", "--", "src/skills"], {
    cwd: repoRoot,
    encoding: "utf8",
  });
  const paths = listing.split("\n").filter(Boolean);
  const records = [];
  for (const relPath of paths) {
    if (!/^src\/skills\/[^/]+\/scripts\/[^/]+\.mjs$/.test(relPath)) continue;
    if (relPath.endsWith(".test.mjs")) continue;
    const source = readFileSync(join(repoRoot, relPath), "utf8");
    records.push({ name: relPath, source });
  }
  return records.sort((a, b) => a.name.localeCompare(b.name));
}

// Everything below is this script's own DRIVER and runs only when this file
// is the process entry point -- see check-npm-packages.mjs's own comment for
// why this guard exists and what it protects against.
const IS_ENTRY_POINT = process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (IS_ENTRY_POINT) {
  const errors = [];

  const tracked = skillScriptFilesFromTrackedTree(ROOT);
  const packed = skillScriptFilesFromPackedTarball(join(ROOT, "installer"));

  if (tracked.length === 0) {
    errors.push("tracked-tree route enumerated ZERO skill scripts -- refusing to treat that as a clean tree");
  }
  if (packed.length === 0) {
    errors.push("packed-tarball route enumerated ZERO skill scripts -- refusing to treat that as a clean tree");
  }

  if (tracked.length > 0) {
    const violations = skillScriptSpawnViolations(tracked);
    if (!Array.isArray(violations)) {
      errors.push(`tracked-tree route: ${violations.message}`);
    } else {
      for (const v of violations) {
        errors.push(`tracked-tree (${v.file}): ${v.fn}(${v.command}, ...) -- ${v.reason}`);
      }
    }
  }

  if (packed.length > 0) {
    const violations = skillScriptSpawnViolations(packed);
    if (!Array.isArray(violations)) {
      errors.push(`packed-tarball route: ${violations.message}`);
    } else {
      for (const v of violations) {
        errors.push(`packed-tarball (${v.file}): ${v.fn}(${v.command}, ...) -- ${v.reason}`);
      }
    }
  }

  if (errors.length) {
    console.error("check-no-skill-external-spawn: FAIL");
    for (const e of errors) console.error("  - " + e);
    process.exit(1);
  }

  console.log(
    `check-no-skill-external-spawn: OK -- tracked-tree ${tracked.length} files, packed-tarball ${packed.length} files`,
  );
}
